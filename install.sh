ensure_node() {
  local ok=0 major=0
  if command -v node >/dev/null 2>&1 && command -v npm >/dev/null 2>&1; then
    major="$(node -p 'process.versions.node.split(".")[0]' 2>/dev/null || echo 0)"
    [[ "$major" -ge 18 ]] && ok=1
  fi
  [[ "$ok" -eq 1 ]] && return 0

  command -v apt-get >/dev/null 2>&1 || fail "Node.js 18+ dan npm diperlukan untuk Orkut bridge. Install Node.js lalu jalankan installer lagi."
  info "Memasang Node.js 22 untuk bridge Orkut..."
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -y >/dev/null
  apt-get install -y ca-certificates curl gnupg >/dev/null
  curl -fsSL https://deb.nodesource.com/setup_22.x | bash - >/dev/null
  apt-get install -y nodejs >/dev/null
  command -v node >/dev/null 2>&1 && command -v npm >/dev/null 2>&1 || fail "Node.js/npm gagal dipasang."
}

